import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import sharp from 'sharp';
import { paletteCSS } from '../src/palette.js';

const root = fileURLToPath(new URL('../', import.meta.url));
const images = {};
for (const id of ['butler', 'detective', 'sleepy']) {
  const png = `${root}assets/lulu-${id}.png`;
  const output = `${root}assets/lulu-${id}.webp`;
  const source = sharp(png);
  const meta = await source.metadata();
  if (!meta.hasAlpha) throw new Error(`${png}: alpha channel required`);
  await source.resize({ width: 600, withoutEnlargement: true }).webp({ quality: 92, alphaQuality: 100, effort: 6 }).toFile(output);
  images[id] = `data:image/webp;base64,${(await readFile(output)).toString('base64')}`;
}
const styles = await readFile(`${root}src/theme.css`, 'utf8');
await writeFile(`${root}src/generated.js`, `// Generated by scripts/build.mjs\nexport const IMAGES=${JSON.stringify(images)};\nexport const STYLES=${JSON.stringify(styles)};\n`);
await mkdir(`${root}lib`, { recursive: true });
const built = await build({
  entryPoints: [`${root}src/plugin.js`], bundle: true, write: false, minify: true,
  format: 'cjs', platform: 'browser', target: ['chrome110'], external: ['react'],
});
const wrapper = `/* 噜噜 · 小管家 v1.0.0 | DSH native theme plugin */\nwindow.__ModuleLoader__.load({id:"dsh-lulu-butler-theme",factory:function(require){var module={exports:{}};var exports=module.exports;\n${built.outputFiles[0].text}\nreturn module.exports;}});\n`;
await writeFile(`${root}lib/client.js`, wrapper);
await writeFile(`${root}lib/lulu-theme.css`, `${paletteCSS()}\n${styles}`);
await build({
  entryPoints: [`${root}preview/app.jsx`], bundle: true, minify: true,
  outfile: `${root}preview/app.js`, format: 'iife', platform: 'browser',
  target: ['chrome110'], define: { 'process.env.NODE_ENV': '"production"' },
});
console.log(`Built native plugin: ${(Buffer.byteLength(wrapper) / 1024).toFixed(0)} KiB; 3 transparent outfits; light + dark tokens.`);
