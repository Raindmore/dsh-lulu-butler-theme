import { readFile, writeFile, mkdir, stat } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import sharp from 'sharp';
import { paletteCSS } from '../src/palette.js';
const root = fileURLToPath(new URL('../', import.meta.url));
const assets = { scene: ['study-hero', 1600], face: ['lulu-face', 400], night: ['study-hero-night', 1600] };
const images = {};
for (const [key, [filename, width]] of Object.entries(assets)) {
  const png = `${root}assets/${filename}.png`;
  const output = `${root}assets/${filename}.webp`;
  let hasOriginal = true;
  try { await stat(png); } catch { hasOriginal = false; }
  const source = hasOriginal ? png : output;
  try { await stat(source); } catch { throw new Error(`Missing asset: ${source}`); }
  if (key === 'face' && !(await sharp(source).metadata()).hasAlpha) throw new Error('Mascot face must retain transparency');
  if (hasOriginal) await sharp(png).resize({ width, withoutEnlargement: true }).webp({ quality: key === 'face' ? 94 : 89, alphaQuality: 100, effort: 5 }).toFile(output);
  images[key] = `data:image/webp;base64,${(await readFile(output)).toString('base64')}`;
}
if (!images.night) images.night = images.scene;
const styles = await readFile(`${root}src/theme.css`, 'utf8');
await writeFile(`${root}src/generated.js`, `// Generated by scripts/build.mjs\nexport const IMAGES=${JSON.stringify(images)};\nexport const STYLES=${JSON.stringify(styles)};\n`);
await mkdir(`${root}lib`, { recursive: true });
const built = await build({ entryPoints: [`${root}src/plugin.js`], bundle: true, write: false, minify: true, format: 'cjs', platform: 'browser', target: ['chrome110'], external: ['react'] });
const wrapper = `/* 噜噜 · 暖橙书房 1.0 | Native DSH theme */\nwindow.__ModuleLoader__.load({id:"dsh-lulu-warm-study-theme",factory:function(require){var module={exports:{}};var exports=module.exports;\n${built.outputFiles[0].text}\nreturn module.exports;}});\n`;
await writeFile(`${root}lib/client.js`, wrapper);
await writeFile(`${root}lib/warm-study.css`, `${paletteCSS()}\n${styles}`);
await build({ entryPoints: [`${root}preview/app.jsx`], bundle: true, minify: true, outfile: `${root}preview/app.js`, format: 'iife', platform: 'browser', target: ['chrome110'], define: { 'process.env.NODE_ENV': '"production"' } });
console.log(`Built warm-study 1.0: ${(Buffer.byteLength(wrapper) / 1024).toFixed(0)} KiB, prebuilt native plugin + matching preview.`);
